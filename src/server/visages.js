// « Face Research Lab London Set » — Lisa DeBruine et Benedict Jones,
// université de Glasgow. 102 personnes photographiées en studio.
//   https://doi.org/10.6084/m9.figshare.5047666.v5
//   Licence CREATIVE COMMONS BY 4.0 — https://creativecommons.org/licenses/by/4.0/
//
// LA LICENCE EST LA RAISON PRINCIPALE DE CE CHOIX. Presque toutes les bases de
// visages à fond uniforme sont réservées à la recherche : FEI l'écrit noir sur
// blanc (« available for research purposes only »), Chicago, KDEF et Radboud
// demandent une autorisation pour tout autre usage. Un jeu diffusé en public
// n'est pas de la recherche. CC BY autorise cet usage, y compris commercial, à
// la seule condition de citer la source — ce que fait ce fichier, et ce que
// devrait aussi faire un générique à l'antenne.
//
// LA SECONDE RAISON EST LE JEU LUI-MÊME. Ces portraits sont pris dans des
// conditions rigoureusement identiques : même fond gris, même éclairage, même
// cadrage, expression neutre, et T-SHIRT BLANC POUR TOUT LE MONDE. Rien
// d'autre que le visage ne distingue deux images — or c'est exactement ce que
// le jeu demande. Un fond qui change, un vêtement reconnaissable, une lumière
// différente : autant de repères de mémoire qui remplaceraient la
// reconnaissance des visages par la reconnaissance des décors.
//
// CE QUE NOUS AVONS FAIT AUX IMAGES : un recadrage carré à 80 % du cadre
// d'origine, calé un peu au-dessus du centre pour garder les cheveux, puis un
// redimensionnement à 512 px et une conversion en WebP. NI le fond, NI la
// lumière, NI les visages n'ont été retouchés — la source est déjà régulière,
// et toute retouche n'aurait pu que casser cette régularité.
//
// ============================================================================
// L'EFFECTIF, ET CE QU'IL COÛTE
// ============================================================================
//
// 102 personnes, là où 300 avaient été demandées. Ce n'est pas un
// arbitrage : c'est le plafond de ce qui est disponible sous une licence
// autorisant la diffusion publique. Une série en consomme 29.
//   - deux manches dans une soirée : 58 visages, aucun ne se répète ;
//   - trois manches : 87 visages, on frôle le fond du bassin ;
//   - quatre manches : des visages reviendront d'une manche à l'autre.
// Rien ne casse — le visage doublé se tire dans chaque manche indépendamment —
// mais un joueur peut croire reconnaître quelqu'un vu à la manche précédente.
//
// POUR ALLER AU-DELÀ : la Chicago Face Database compte 597 personnes dans les
// mêmes conditions de studio, et son équipe accorde l'usage hors recherche sur
// demande. C'est une lettre à écrire, pas une difficulté technique. Le jour où
// l'autorisation arrive, seul ce fichier change.

